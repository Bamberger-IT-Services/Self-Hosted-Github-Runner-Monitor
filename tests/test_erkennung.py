class Attrappe(erkennung.Quelle):
    """Quelle ohne systemctl, journalctl und Netz."""

    def __init__(self, wurzel, aktiv=None, journal=None, antworten=None, netz=True):
        super().__init__(wurzel, netz=netz)
        self._aktiv = aktiv or {}
        self._journal = journal or {}
        self._antworten = antworten or {}
        self.abfragen: list[str] = []

    def aktiv(self, unit):
        return self._aktiv.get(unit)

    def journal(self, unit):
        return self._journal.get(unit, [])

    def hole(self, url):
        self.abfragen.append(url)
        return self._antworten.get(url)


