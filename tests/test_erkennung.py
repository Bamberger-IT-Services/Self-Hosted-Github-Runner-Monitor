class Basis(unittest.TestCase):
    def setUp(self):
        self._verz = tempfile.TemporaryDirectory()
        self.vm = VM(Path(self._verz.name))

    def tearDown(self):
        self._verz.cleanup()

    def erkenne(self, **quelle):
        q = Attrappe(self.vm.w, **quelle)
        self.q = q
        with mock.patch.object(erkennung.subprocess, "run", side_effect=AssertionError("kein Befehl erlaubt")), \
             mock.patch.object(erkennung.subprocess, "Popen", side_effect=AssertionError("kein Befehl erlaubt")):
            ergebnis = erkennung.erkenne(quelle=q, runner_verz="/opt/actions-runner",
                                         token_datei=self.vm.w / "etc/runner-monitor/github-token",
                                         zuordnung_datei=self.vm.w / "etc/runner-monitor/runner.json")
        self.ergebnis = ergebnis
        self.alles = json.dumps(ergebnis, ensure_ascii=False) + erkennung.als_text(ergebnis, farbe=True, einrichtung=True)
        for geheim in (GEHEIM_FORGEJO, GEHEIM_GITLAB, GEHEIM_GITHUB):
            self.assertNotIn(geheim, self.alles)
        return {f["id"]: f for f in ergebnis["runner"]}


