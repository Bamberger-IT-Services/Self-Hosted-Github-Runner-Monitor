class VM:
    """Baut eine VM im Temp-Ordner nach (Pfade wie auf der VM, z. B. ``/etc/systemd/system``)."""

    def __init__(self, wurzel: Path) -> None:
        self.w = wurzel

    def datei(self, pfad: str, inhalt, modus: int | None = None) -> Path:
        ziel = self.w / pfad.lstrip("/")
        ziel.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(inhalt, str):
            inhalt = inhalt.encode("utf-8")
        ziel.write_bytes(inhalt)
        if modus is not None:
            os.chmod(ziel, modus)
        return ziel

    def unit(self, name: str, text: str, aktiviert: bool = True, verz: str = "/etc/systemd/system") -> None:
        self.datei(f"{verz}/{name}", text)
        if aktiviert:
            wants = self.w / "etc/systemd/system/multi-user.target.wants"
            wants.mkdir(parents=True, exist_ok=True)
            (wants / name).symlink_to(f"{verz}/{name}")

    def prozess(self, pid: int, argv: list, unit: str | None = None, cwd: str | None = None, cgroup: str | None = None) -> None:
        roh = b"\0".join(a.encode("utf-8") if isinstance(a, str) else a for a in argv) + b"\0"
        self.datei(f"/proc/{pid}/cmdline", roh)
        self.datei(f"/proc/{pid}/cgroup", cgroup if cgroup is not None else (f"0::/system.slice/{unit}\n" if unit else "0::/user.slice/user-1000.slice/session-3.scope\n"))
        if cwd:
            (self.w / f"proc/{pid}/cwd").symlink_to(cwd)

    # ------------------------------------------------ fertige Runner

    def github(self, verz: str = "/opt/actions-runner", name: str = "runner-vm-01", pid: int = 1201) -> str:
        unit = f"actions.runner.beispiel-org.{name}.service"
        self.unit(unit, f"[Unit]\nDescription=GitHub Actions Runner (beispiel-org.{name})\n\n[Service]\n"
                        f"ExecStart={verz}/runsvc.sh\nUser=runner\nWorkingDirectory={verz}\nKillMode=process\n")
        runner = {"agentId": 7, "agentName": name, "poolId": 1, "poolName": "Default",
                  "serverUrl": "https://pipelines.actions.githubusercontent.com/x",
                  "gitHubUrl": "https://github.com/beispiel-org", "workFolder": "_work"}
        self.datei(f"{verz}/.runner", "﻿" + json.dumps(runner))
        self.datei(f"{verz}/.credentials", json.dumps({"scheme": "OAuth", "data": {"token": GEHEIM_GITHUB}}))
        self.datei(f"{verz}/bin/Runner.Listener.deps.json", json.dumps({"libraries": {"Runner.Listener/2.338.1": {}}}))
        self.prozess(pid, [f"{verz}/bin/Runner.Listener", "run", "--startuptype", "service"], unit=unit, cwd=verz)
        return unit

    def forgejo(self, binaer: str = "forgejo-runner", unit: str = "forgejo-runner.service", pid: int = 1302,
                verz: str = "/var/lib/forgejo-runner", adresse: str = "https://git.example.org") -> str:
        self.unit(unit, f"[Unit]\nDescription=Forgejo Runner\n[Service]\nExecStart=/usr/local/bin/{binaer} daemon "
                        f"--config /etc/forgejo-runner/config.yml\nWorkingDirectory={verz}\nUser=runner\n")
        self.datei("/etc/forgejo-runner/config.yml", "log:\n  level: info\nrunner:\n  file: .runner\n  capacity: 1\n")
